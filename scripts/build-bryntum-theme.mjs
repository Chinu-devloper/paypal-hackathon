// Regenerates src/styles/bryntum-theme.css: Bryntum's Stockholm light and dark themes, each scoped to html.light / html.dark
// so the Gantt follows the app theme at runtime. Run after upgrading @bryntum/gantt.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import postcss from "postcss";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("@bryntum/gantt/package.json"));

function scope(css, theme) {
  const root = postcss.parse(css);
  root.walkAtRules("charset", (r) => r.remove());
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
    const selectors = rule.selectors
      .filter((s) => !s.startsWith(":host"))
      .map((s) => (s.startsWith(":root") ? s.replace(":root", `html.${theme}`) : `html.${theme} ${s}`));
    if (selectors.length === 0) rule.remove();
    else rule.selectors = selectors;
  });
  return root.toString();
}

const parts = ["light", "dark"].map((theme) => scope(readFileSync(join(pkgDir, `stockholm-${theme}.css`), "utf8"), theme));
const out = join(process.cwd(), "src", "styles", "bryntum-theme.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `/* Generated by scripts/build-bryntum-theme.mjs. Do not edit. */\n${parts.join("\n")}\n`);
console.log(`Wrote ${out}`);
